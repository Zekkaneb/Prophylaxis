/**
 * Compiles the supplied Brandon Tran repertoire PGNs into a position-keyed
 * book. Run with `node scripts/build-brandon-book.mjs`.
 *
 * Every chapter is a game; the parser keeps its full variation tree. This
 * script walks that tree, validates every SAN against chess.js (including
 * chapters that start from a FEN), and records only the moves Brandon plays.
 * Positions are keyed by board + side to move + castling rights, so
 * transpositions merge without flattening the source.
 */
import fs from 'node:fs';
import path from 'node:path';
import { Chess } from 'chess.js';
import { parsePgn } from '../src/pgn/parser.ts';
import { bookKey } from '../src/play/personality/repertoires/book.ts';
import { STANDARD_START_FEN } from '../src/play/pgn.ts';

const SOURCES = [
  { file: 'repertoires/G4gISY53.pgn', id: 'vienna', color: 'w', tags: ['sharp', 'initiative'] },
  { file: 'repertoires/sicilian-ne2.pgn', id: 'sicilian', color: 'w', tags: ['sharp', 'initiative'] },
  { file: 'repertoires/BTujsxIs.pgn', id: 'austrian', color: 'w', tags: ['sharp', 'initiative'] },
  { file: 'repertoires/cpULfWpl.pgn', id: 'french', color: 'b', tags: ['positional', 'initiative'] },
  { file: 'repertoires/HlS091Xs.pgn', id: 'gruenfeld', color: 'b', tags: ['sharp', 'initiative'] },
];

const book = new Map();
const issues = [];
const chapters = [];
let nodes = 0;
let variations = 0;

function slug(text) {
  return String(text || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 48);
}

function addMove(key, move, meta) {
  let list = book.get(key);
  if (!list) {
    list = new Map();
    book.set(key, list);
  }
  const uci = `${move.from}${move.to}${move.promotion ?? ''}`;
  const existing = list.get(uci);
  if (existing) {
    existing.weight = Math.max(existing.weight, meta.weight);
    for (const tag of meta.tags) if (!existing.tags.includes(tag)) existing.tags.push(tag);
    if (!existing.lineIds.includes(meta.lineId)) existing.lineIds.push(meta.lineId);
    return;
  }
  list.set(uci, {
    uci,
    san: move.san,
    tags: [...meta.tags],
    weight: meta.weight,
    lineIds: [meta.lineId],
  });
}

for (const source of SOURCES) {
  const text = fs.readFileSync(source.file, 'utf8');
  const parsed = parsePgn(text);
  for (const game of parsed.games) {
    const startFen = game.headers.FEN?.trim() || STANDARD_START_FEN;
    let board;
    try {
      board = new Chess(startFen);
    } catch {
      issues.push({ source: source.id, chapter: game.headers.ChapterName, message: 'invalid FEN' });
      continue;
    }
    if (game.root.children.length === 0) continue;
    /* Intro/conclusion chapters are prose with sample sidelines (the Vienna
       intro even shows a 1.d4 game), not part of the repertoire. */
    if (/introduction|conclusion/i.test(game.headers.ChapterName ?? '')) continue;

    const chapterId = `brandon-${source.id}-${slug(game.headers.ChapterName) || game.index}`;
    chapters.push({
      id: chapterId,
      study: game.headers.StudyName || source.id,
      name: game.headers.ChapterName || `Chapter ${game.index + 1}`,
      startFen,
      moves: 0,
      branches: 0,
    });
    const chapter = chapters[chapters.length - 1];

    // Mark mainline nodes so variations can be counted and weighted down.
    const mainline = new Set();
    let cursor = game.root;
    while (cursor.children.length > 0) {
      cursor = cursor.children[0];
      mainline.add(cursor);
    }

    const walk = (node, position, depth) => {
      for (const child of node.children) {
        const local = new Chess(position.fen());
        const before = local.fen();
        let move;
        try {
          move = local.move(child.san);
        } catch {
          issues.push({
            source: source.id,
            chapter: chapter.name,
            ply: depth,
            san: child.san,
            message: 'illegal SAN',
          });
          continue;
        }
        if (!move) {
          issues.push({
            source: source.id,
            chapter: chapter.name,
            ply: depth,
            san: child.san,
            message: 'rejected by chess.js',
          });
          continue;
        }

        nodes += 1;
        chapter.moves += 1;
        const isMain = mainline.has(child);
        if (!isMain) {
          variations += 1;
          chapter.branches += 1;
        }

        if (move.color === source.color) {
          addMove(bookKey(before), move, {
            tags: source.tags,
            weight: isMain ? 3 : 1,
            lineId: chapterId,
          });
        }
        walk(child, local, depth + 1);
      }
    };
    walk(game.root, board, 0);
  }
}

const entries = [];
for (const [key, list] of book) {
  for (const entry of list.values()) entries.push({ key, ...entry });
}

const output = `/**
 * Brandon Tran's opening book — generated by scripts/build-brandon-book.mjs.
 *
 * Source: the supplied Lichess studies (Vienna Game, Pirc Austrian Attack,
 * French Defence, Grünfeld Defence) plus the supplied Sicilian 2.Ne2 move
 * order. Each chapter's variation tree was validated with chess.js and
 * collapsed into position → Brandon's move, so branches and transpositions
 * work without storing a linear game. Do not edit by hand: rerun the script.
 */
import type { OpeningTag } from '../styles.ts';

export interface BrandonBookEntry {
  key: string;
  uci: string;
  san: string;
  tags: OpeningTag[];
  weight: number;
  lineIds: string[];
}

export const BRANDON_BOOK_STATS = ${JSON.stringify(
  {
    chapters: chapters.length,
    nodes,
    variations,
    positions: book.size,
    moves: entries.length,
    sources: SOURCES.map((source) => source.file),
    issues,
  },
  null,
  2,
)} as const;

export const BRANDON_BOOK: readonly BrandonBookEntry[] = ${JSON.stringify(entries, null, 2)};
`;

const target = path.join('src', 'play', 'personality', 'repertoires', 'brandonBook.ts');
fs.writeFileSync(target, output);
